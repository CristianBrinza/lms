/** A plain lookup: `usePlanT` in components, `planT` in helpers outside them. */
export const planT = messages({ en, ro, ru });
export const usePlanT = planT;

// ---------------------------------------------------------------- days, from Intl

const format = (day: string, options: Intl.DateTimeFormatOptions) =>
  new Intl.DateTimeFormat(intlLocale(), options).format(parseDay(day));

/** Romanian and Russian write weekdays in lower case; at the start of a label they lead. */
const capital = (text: string) =>
  getLocale() === 'en' ? text : text.charAt(0).toLocaleUpperCase(intlLocale()) + text.slice(1);

/** "Mon", "Lun.", "Пн". */
export const weekdayShort = (day: string) => capital(format(day, { weekday: 'short' }));
/** "5 Oct", "5 oct.", "5 окт.". */
export const dayAndMonth = (day: string) => format(day, { day: 'numeric', month: 'short' });
/** "Monday 5 October", "Luni, 5 octombrie", "Понедельник, 5 октября". */
export const dayLong = (day: string) =>
  capital(format(day, { weekday: 'long', day: 'numeric', month: 'long' }));

/** "Today", "Tomorrow", "Yesterday", else "Mon, 5 Oct" — in the current language. */
export function relativeDay(day: string, today = localDate()): string {
  const t = planT();
  const diff = daysBetween(today, day);
  if (diff === 0) return t.today;
  if (diff === 1) return t.tomorrow;
  if (diff === -1) return t.yesterday;
  return `${weekdayShort(day)}, ${dayAndMonth(day)}`;
}

/** relativeDay inside a sentence: "today", "tomorrow", but "Tue, 6 Oct" keeps its capital. */
export function relativeDayInline(day: string, today = localDate()): string {
  const t = planT();
  const diff = daysBetween(today, day);
  if (diff === 0) return t.todayInline;
  if (diff === 1) return t.tomorrowInline;
  if (diff === -1) return t.yesterdayInline;
  return `${weekdayShort(day)}, ${dayAndMonth(day)}`;
}

/** "21:40" in the current language's clock. */
export const clockTime = (iso: string) =>
  new Date(iso).toLocaleTimeString(intlLocale(), { hour: '2-digit', minute: '2-digit' });
