const english = (key: string) => {
  const words = key.replace(/-/g, ' ');
  return words.charAt(0).toUpperCase() + words.slice(1);
};

/** An icon's name in the current language: "Bell pepper", "Ardei gras", "Болгарский перец". */
export function iconLabel(key: string): string {
  const locale = getLocale();
  if (locale === 'ro') return NAMES[key]?.[0] ?? BRANDS_RO[key] ?? EN[key] ?? english(key);
  if (locale === 'ru') return NAMES[key]?.[1] ?? BRANDS_RU[key] ?? EN[key] ?? english(key);
  return EN[key] ?? english(key);
}
