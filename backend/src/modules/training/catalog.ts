export interface ExercisePreset {
  key: string;
  name: string;
  category: ExerciseCategory;
  muscles: Muscle[];
  secondary?: Muscle[];
  /** Alternatives, each a set of kinds needed together. [] = nothing needed. */
  equipment: string[][];
  measure: Measure;
  /** Takes a weight (kg) when there is one. */
  weighted?: boolean;
  /** One side at a time: each set is done left and right. */
  unilateral?: boolean;
  reps?: number;
  seconds?: number;
  /** Metres, for distance exercises. */
  distance?: number;
  rest?: number;
  /** 1 easy, 2 some practice, 3 hard. */
  level: 1 | 2 | 3;
  /** Jumps and landings: the neighbours downstairs hear it. */
  impact?: 'low' | 'high';
  icon: string;
  steps: string[];
  /** Ways to do it: grips, stances, positions. Equipment pieces (bands, bar grips) add theirs. */
  variants?: string[];
}

